using V2f = sf::Vector2f;
using PolygonData = std::vector<V2f>; // A list of vertices defining the polygon
//NOTE : if 1st vertex is SOLID_V2F (defined in conbex_polygon.hpp as
// sf::Vector2f(-1.0f, -1.0f) ), then the polygon is considered solid and this point is discarded!
using LineData =
    std::array<V2f, 2>; // A line segment always has exactly 2 vertices

struct LevelData {
  std::vector<PolygonData> polygons;
  std::vector<LineData> lines;
};

struct Level {
  Polygons polygons;
  size_t total_alive_polygon = 0;
  std::vector<LineData> lines;
  Level(const LevelData &data) {
    for (const auto &poly_data : data.polygons) {
      polygons.emplace_back(ConvexPolygon(poly_data));
      if (poly_data[0]!=SOLID_V2F) total_alive_polygon++;
    }
    for (const auto &line_data : data.lines){
        lines.emplace_back(line_data);
    }
  }
  
  size_t get_alive_poly_count(){
      size_t alive = 0;
      for (const auto& poly: polygons){
          if (poly.is_mortal) alive++;
      }
      return alive;
  }
  
};

